"""Generate selected conversation-view TypeScript from its canonical Python types."""

from __future__ import annotations

import argparse
import dataclasses
import importlib
import json
import types
from enum import Enum
from pathlib import Path
from typing import Literal, TypeAliasType, get_args, get_origin, get_type_hints, is_typeddict

ROOT = Path(__file__).resolve().parents[1]


def generate() -> str:
    module = importlib.import_module("planner.conversation.views.contracts")
    declarations: dict[str, str] = {}
    visiting: set[str] = set()

    def describe(annotation: object) -> str:
        origin = get_origin(annotation)
        args = get_args(annotation)
        if origin is Literal:
            return " | ".join(json.dumps(value) for value in args)
        if origin in (list, tuple):
            return f"Array<{describe(args[0])}>"
        if origin in (types.UnionType, __import__("typing").Union):
            return " | ".join(describe(part) for part in args)
        primitive = {
            str: "string",
            int: "number",
            float: "number",
            bool: "boolean",
            type(None): "null",
        }
        if annotation in primitive:
            return primitive[annotation]
        name = str(getattr(annotation, "__name__", ""))
        if name in declarations or name in visiting:
            return name
        visiting.add(name)
        if isinstance(annotation, TypeAliasType):
            declarations[name] = f"export type {name} = {describe(annotation.__value__)};"
        elif isinstance(annotation, type) and issubclass(annotation, Enum):
            declarations[name] = (
                f"export type {name} = "
                + " | ".join(json.dumps(entry.value) for entry in annotation)
                + ";"
            )
        elif is_typeddict(annotation) or (
            isinstance(annotation, type) and dataclasses.is_dataclass(annotation)
        ):
            fields = get_type_hints(annotation)
            if dataclasses.is_dataclass(annotation):
                fields = {
                    field.name: fields[field.name] for field in dataclasses.fields(annotation)
                }
            declarations[name] = (
                f"export interface {name} {{\n"
                + "".join(f"  {key}: {describe(value)};\n" for key, value in fields.items())
                + "}"
            )
        else:
            raise TypeError(f"Unsupported conversation view annotation: {annotation!r}")
        visiting.remove(name)
        return name

    for value in vars(module).values():
        if getattr(value, "__module__", None) == module.__name__ and (
            is_typeddict(value) or isinstance(value, TypeAliasType)
        ):
            describe(value)
    return (
        "// Generated by scripts/generate_conversation_view_contracts.py. Do not edit.\n"
        f"export const VIEW_PROTOCOL_VERSION = {module.VIEW_PROTOCOL_VERSION};\n"
        f"export const VIEW_PROJECTION_VERSION = {module.VIEW_PROJECTION_VERSION};\n\n"
        + "\n\n".join(declarations.values())
        + "\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    from pydantic import TypeAdapter

    from planner.conversation.views.contracts import ViewRowBody

    schema_target = ROOT / "web/src/lib/conversation/view/bodySchema.ts"
    schema_content = (
        "// Generated from the canonical ViewRowBody. Do not edit.\nexport default "
        + json.dumps(TypeAdapter(ViewRowBody).json_schema(), separators=(",", ":"))
        + ";\n"
    )
    if arguments.check:
        if not schema_target.exists() or schema_target.read_text() != schema_content:
            raise SystemExit("Conversation body schema drifted. Regenerate contracts.")
    else:
        schema_target.write_text(schema_content)
    target = ROOT / "web/src/lib/conversation/view/contracts.ts"
    content = generate()
    if arguments.check:
        if not target.exists() or target.read_text() != content:
            raise SystemExit("Conversation view contracts drifted. Regenerate contracts.ts.")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)


if __name__ == "__main__":
    main()
