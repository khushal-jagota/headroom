"""Generate browser TypeScript types from canonical TypedDicts."""

from __future__ import annotations

import argparse
import importlib
import json
import types
from pathlib import Path
from typing import Literal, TypeAliasType, get_args, get_origin, get_type_hints, is_typeddict

ROOT = Path(__file__).resolve().parents[1]
MODULES = (
    "contracts",
    "delivery_contracts",
    "views.contracts",
    "review_contracts",
)


def generate() -> str:
    definitions: set[str] = set()
    declarations: list[str] = []

    def describe(annotation: object) -> str:
        if is_typeddict(annotation):
            name = str(getattr(annotation, "__name__", ""))
            return name
        if isinstance(annotation, TypeAliasType):
            return annotation.__name__
        origin = get_origin(annotation)
        args = get_args(annotation)
        if origin is Literal:
            return " | ".join(json.dumps(x) for x in args)
        if origin is list:
            return f"Array<{describe(args[0])}>"
        if origin in (types.UnionType, __import__("typing").Union):
            parts = [describe(x) for x in args]
            return " | ".join(parts)
        primitives = {str: "string", int: "number", bool: "boolean", type(None): "null"}
        if annotation in primitives:
            value = primitives[annotation]
            return value
        raise TypeError(annotation)

    for name in MODULES:
        module = importlib.import_module(f"planner.navigation.{name}")
        for key, value in vars(module).items():
            if key in definitions:
                continue
            if is_typeddict(value) and value.__module__ == module.__name__:
                fields = {k: describe(v) for k, v in get_type_hints(value).items()}
                definitions.add(key)
                declarations.append(
                    "export interface "
                    + key
                    + " {\n"
                    + "".join(f"  {k}: {t};\n" for k, t in fields.items())
                    + "}"
                )
            elif isinstance(value, TypeAliasType) or get_origin(value) is Literal:
                ts = describe(
                    value.__value__ if isinstance(value, TypeAliasType) else value
                )
                definitions.add(key)
                declarations.append(f"export type {key} = {ts};")
    navigation = importlib.import_module("planner.navigation.contracts")
    delivery = importlib.import_module("planner.navigation.delivery_contracts")
    views = importlib.import_module("planner.navigation.views.contracts")
    constants = (
        f"export const WIRE_VERSION = {delivery.WIRE_VERSION};\n"
        f"export const VIEW_WIRE_VERSION = {views.VIEW_WIRE_VERSION};\n"
        f"export const VIEW_PROJECTION_VERSION = {views.VIEW_PROJECTION_VERSION};\n"
        f"export const SCHEMA_VERSION = {navigation.SCHEMA_VERSION};\n"
        f"export const SUPPORTED_SEMANTICS = {json.dumps(navigation.SUPPORTED_SEMANTICS)};\n"
    )
    return (
        "// Generated by scripts/generate_navigation_browser_contracts.py. Do not edit.\n"
        + constants
        + "\n\n".join(declarations)
        + "\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "web/src/lib/navigation/contracts.ts"
    content = generate()
    if args.check:
        if target.read_text() != content:
            raise SystemExit("Browser navigation contracts drifted. Regenerate contracts.ts.")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)


if __name__ == "__main__":
    main()
