"""Generate browser contracts and the native Ticket decoder from canonical TypedDicts."""

from __future__ import annotations

import argparse
import importlib
import json
import types
from pathlib import Path
from typing import Literal, TypeAliasType, get_args, get_origin, get_type_hints, is_typeddict

ROOT = Path(__file__).resolve().parents[1]
MODULES = (
    "contracts",
    "delivery_contracts",
    "views.contracts",
    "review_contracts",
)


def generate() -> str:
    definitions: set[str] = set()
    declarations: list[str] = []

    def describe(annotation: object) -> str:
        if is_typeddict(annotation):
            name = str(getattr(annotation, "__name__", ""))
            return name
        if isinstance(annotation, TypeAliasType):
            return annotation.__name__
        origin = get_origin(annotation)
        args = get_args(annotation)
        if origin is Literal:
            return " | ".join(json.dumps(x) for x in args)
        if origin is list:
            return f"Array<{describe(args[0])}>"
        if origin in (types.UnionType, __import__("typing").Union):
            parts = [describe(x) for x in args]
            return " | ".join(parts)
        primitives = {str: "string", int: "number", bool: "boolean", type(None): "null"}
        if annotation in primitives:
            value = primitives[annotation]
            return value
        raise TypeError(annotation)

    for name in MODULES:
        module = importlib.import_module(f"planner.navigation.{name}")
        for key, value in vars(module).items():
            if key in definitions:
                continue
            if is_typeddict(value) and value.__module__ == module.__name__:
                fields = {k: describe(v) for k, v in get_type_hints(value).items()}
                definitions.add(key)
                declarations.append(
                    "export interface "
                    + key
                    + " {\n"
                    + "".join(f"  {k}: {t};\n" for k, t in fields.items())
                    + "}"
                )
            elif isinstance(value, TypeAliasType) or get_origin(value) is Literal:
                ts = describe(
                    value.__value__ if isinstance(value, TypeAliasType) else value
                )
                definitions.add(key)
                declarations.append(f"export type {key} = {ts};")
    navigation = importlib.import_module("planner.navigation.contracts")
    delivery = importlib.import_module("planner.navigation.delivery_contracts")
    views = importlib.import_module("planner.navigation.views.contracts")
    constants = (
        f"export const WIRE_VERSION = {delivery.WIRE_VERSION};\n"
        f"export const VIEW_WIRE_VERSION = {views.VIEW_WIRE_VERSION};\n"
        f"export const VIEW_PROJECTION_VERSION = {views.VIEW_PROJECTION_VERSION};\n"
        f"export const SCHEMA_VERSION = {navigation.SCHEMA_VERSION};\n"
        f"export const SUPPORTED_SEMANTICS = {json.dumps(navigation.SUPPORTED_SEMANTICS)};\n"
    )
    return (
        "// Generated by scripts/generate_navigation_browser_contracts.py. Do not edit.\n"
        + constants
        + "\n\n".join(declarations)
        + "\n"
    )


NATIVE_START = "// BEGIN GENERATED TICKET CONTRACT"
NATIVE_END = "// END GENERATED TICKET CONTRACT"


def generate_native_ticket() -> str:
    """Merge ordinary and diagnostic Ticket records without inventing a wire shape."""
    views = importlib.import_module("planner.navigation.views.contracts")
    ordinary = get_type_hints(views.ViewTicketValue)
    broken = get_type_hints(views.ViewBrokenTicketValue)
    fields = ordinary | broken

    def describe(annotation: object) -> str:
        if get_origin(annotation) in (types.UnionType, __import__("typing").Union):
            members = [value for value in get_args(annotation) if value is not type(None)]
            if len(members) != 1:
                raise TypeError(annotation)
            return describe(members[0]) + "?"
        if get_origin(annotation) is Literal:
            return "String"
        if is_typeddict(annotation):
            return {
                "PrincipalValue": "ViewPrincipal",
                "NavigationTicketIntegrityIssue": "ViewIntegrityIssue",
                "ViewContentReference": "ViewContentReference",
            }[str(getattr(annotation, "__name__", ""))]
        primitives: dict[object, str] = {str: "String", int: "Int", bool: "Bool"}
        return primitives[annotation]

    declarations = []
    for field, annotation in fields.items():
        # The broken record's literal status does not narrow an ordinary Ticket.
        native_type = describe(ordinary.get(field, annotation))
        if field in {"created_at", "updated_at", "proposal_created_at"}:
            native_type = native_type.replace("Int", "Double")
        # Missing locale is retained as unknown for legacy saved snapshots.
        optional = field not in ordinary or field not in broken or field == "locale"
        if optional and not native_type.endswith("?"):
            native_type += "?"
        name = field.split("_")[0] + "".join(part.title() for part in field.split("_")[1:])
        declarations.append(f"    let {name}: {native_type}")
    return (
        NATIVE_START + "\n"
        "// Generated by scripts/generate_navigation_browser_contracts.py. Do not edit.\n"
        "// Canonical ordinary and broken Ticket fields share this safe decode projection.\n"
        "struct ViewTicketValue: Decodable, Sendable {\n"
        + "\n".join(declarations) + "\n}\n" + NATIVE_END
    )


def main() -> None:
    parser = argparse.ArgumentParser(__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "web/src/lib/navigation/contracts.ts"
    content = generate()
    if args.check:
        if target.read_text() != content:
            raise SystemExit("Browser navigation contracts drifted. Regenerate contracts.ts.")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
    native_target = ROOT / "ios/Panels/Core/Navigation/NavigationViewContracts.swift"
    native = native_target.read_text()
    start = native.index(NATIVE_START)
    end = native.index(NATIVE_END) + len(NATIVE_END)
    generated_native = native[:start] + generate_native_ticket() + native[end:]
    if args.check:
        if native != generated_native:
            raise SystemExit("Native navigation Ticket contract drifted. Regenerate contracts.")
    else:
        native_target.write_text(generated_native)


if __name__ == "__main__":
    main()
