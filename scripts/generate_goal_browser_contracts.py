"""Generate the goal/page browser contract from its canonical Python declarations."""

from __future__ import annotations

import argparse
import dataclasses
import enum
import json
import types
from pathlib import Path
from typing import (
    Literal,
    NotRequired,
    TypeAliasType,
    Union,
    cast,
    get_args,
    get_origin,
    get_type_hints,
    is_typeddict,
)

from planner.goals import contracts


def generate() -> str:
    declarations: dict[str, str] = {}

    def render(value: object) -> str:
        if isinstance(value, TypeAliasType):
            declarations.setdefault(value.__name__, "")
            declarations[value.__name__] = (
                f"export type {value.__name__} = {render(value.__value__)};"
            )
            return value.__name__
        origin = get_origin(value)
        args = get_args(value)
        if origin is NotRequired:
            return render(args[0])
        if origin is tuple and len(args) == 2 and args[1] is not Ellipsis:
            return "[" + ", ".join(render(part) for part in args) + "]"
        if origin in (list, tuple):
            return f"Array<{render(args[0])}>"
        if origin in (types.UnionType, Union):
            return " | ".join(render(part) for part in args)
        if origin is Literal:
            return " | ".join(json.dumps(part) for part in args)
        if isinstance(value, type) and issubclass(value, enum.Enum):
            return " | ".join(json.dumps(item.value) for item in value)
        if is_typeddict(value) or dataclasses.is_dataclass(value):
            name = cast(type, value).__name__
            if name not in declarations:
                declarations[name] = ""
                optional: frozenset[str] = getattr(value, "__optional_keys__", frozenset())
                fields = [
                    f"  {key}"
                    f"{'?' if key in optional or get_origin(kind) is NotRequired else ''}: "
                    f"{render(kind)};"
                    for key, kind in get_type_hints(value, include_extras=True).items()
                ]
                declarations[name] = f"export interface {name} {{\n" + "\n".join(fields) + "\n}"
            return name
        return {str: "string", int: "number", float: "number", bool: "boolean", type(None): "null"}[
            cast(type, value)
        ]

    for value in vars(contracts).values():
        if (
            is_typeddict(value) or isinstance(value, TypeAliasType)
        ) and value.__module__ == contracts.__name__:
            render(value)
    return (
        "// Generated by scripts/generate_goal_browser_contracts.py. Do not edit.\n\n"
        + "\n\n".join(declarations.values())
        + "\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / "web/src/lib/goals/contracts.ts"
    result = generate()
    if args.check:
        if target.read_text() != result:
            raise SystemExit("Goal browser contracts drifted")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(result)
