interface FixtureEvent {
  sequence: number;
  kind: ConversationEventKind;
  payload: unknown;
  created_at: number;
}
interface Fixture {
  name: string;
  stopped: boolean;
  events: FixtureEvent[];
}
interface Oracle {
  source_sha256: string;
  fixtures: {
    name: string;
    projection: Record<string, unknown[]>;
    pages: Record<'focus' | 'full', unknown>;
  }[];
}
const root = resolve(import.meta.dirname, '../..');
const source = readFileSync(resolve(root, 'server/conversation/views/conversation_views.json'));
const fixtures = JSON.parse(source.toString()) as Fixture[];
const oracle = JSON.parse(
  readFileSync(resolve(root, 'server/conversation/views/fixture_oracle.json'), 'utf8'),
) as Oracle;
const table_order = {
  state: 'conversation_id',
  rows: 'sequence',
  turns: 'source_sequence',
  groups: 'source_sequence',
  lookups: 'lookup_kind,lookup_id',
};

// Required fixture proof: the browser fixture alone cannot prove the SQL projection.
// The oracle was generated by the unchanged Python writer/readers for these same inputs.
// Projection 5 changed it once on purpose: Focus heads a turn that did not complete.
// Reuse the existing schema fixture and real write door without another server host.
test('the existing conversation fixtures match Python projection rows and both lens pages', async () => {
  expect(createHash('sha256').update(source).digest('hex')).toBe(oracle.source_sha256);
  expect(fixtures.map((value) => value.name)).toEqual(oracle.fixtures.map((value) => value.name));
  for (let index = 0; index < fixtures.length; index++) {
    const fixture = fixtures[index];
    const expected = oracle.fixtures[index];
    const database = database_fixture();
    const store = new ConversationStorePrimitives(database, { integer_now: () => 100 });
    store.create_conversation(
      new ResolvedConversationStart({
        conversation_id: 'fixture',
        backend_key: parse_backend_instance_id('codex'),
        model: 'fixture-model',
        reasoning_effort: null,
        role_materials: null,
        workspace_folder: '/fixture',
        access: ConversationAccess.full,
      }),
    );
    database.write((tx) => {
      for (const row of fixture.events) {
        const encoded = JSON.stringify(row.payload);
        tx.run(
          'INSERT INTO conversation_events (conversation_id,sequence,kind,payload,created_at) VALUES (?,?,?,?,?)',
          ['fixture', row.sequence, row.kind, encoded, row.created_at],
        );
        append_projection(tx, [
          {
            conversation_id: 'fixture',
            sequence: row.sequence,
            kind: row.kind,
            payload: conversation_event_payload_from_canonical_json(row.kind, encoded),
            created_at: row.created_at,
          },
        ]);
      }
      tx.run('UPDATE conversations SET latest_sequence=? WHERE conversation_id=?', [
        fixture.events.at(-1)?.sequence ?? 0,
        'fixture',
      ]);
    });
    const verify = () => {
      database.read((sql) => {
        for (const [table, order] of Object.entries(table_order)) {
          expect(
            sql.all(`SELECT * FROM conversation_view_${table} ORDER BY ${order}`),
            `${fixture.name}: ${table}`,
          ).toEqual(expected.projection[table]);
        }
        for (const lens of ['focus', 'full'] as const) {
          expect(
            read_page(sql, 'fixture', lens, { stopped: fixture.stopped }),
            `${fixture.name}: ${lens}`,
          ).toEqual(expected.pages[lens]);
        }
      });
    };
    verify();
    // Incremental output alone cannot establish the private-stage/install boundary.
    // Reuse these same ten fixtures, with no additional connected setup or case.
    database.write((tx) => tx.run('UPDATE conversation_view_state SET projection_version=0'));
    await rebuild_one_conversation_view(database, 'fixture');
    verify();
  }
});

// A completed replay alone cannot catch a live append that creates a false current
// projection, or show that opening an archive changes the order between atomic installs.
test('active views finish first and a newly opened archive keeps events written during replay', async () => {
  const database = database_fixture();
  const store = new ConversationStore(database);
  const event = new PromptDiscardedEventPayload({
    content: text_message_content('archive'),
    sender_label: 'owner',
  });
  for (const conversation_id of ['a', 'b', 'c', 'chief']) {
    store.create_conversation(
      new ResolvedConversationStart({
        conversation_id,
        backend_key: parse_backend_instance_id('codex'),
        model: 'model',
        reasoning_effort: null,
        role_materials: null,
        workspace_folder: '/workspace',
        access: 'full',
      }),
    );
    store.append_events(conversation_id, [event]);
  }
  database.write((tx) => {
    tx.run(
      "INSERT OR REPLACE INTO agents(agent_key,conversation_id) VALUES ('chief_of_staff','chief')",
    );
    tx.run('DELETE FROM conversation_view_state');
    tx.run('CREATE TABLE install_order(id TEXT)');
    tx.run(
      'CREATE TEMP TRIGGER observe_install AFTER INSERT ON main.conversation_view_state BEGIN INSERT INTO install_order VALUES (NEW.conversation_id); END',
    );
  });
  const rebuilder = new ConversationViewRebuilder();
  await rebuilder.prepare_active(database);
  expect(out_of_date_conversation_ids(database)).toEqual(['a', 'b', 'c']);
  rebuilder.start(database);
  try {
    // The first replay yielded after reading its original high-water mark.
    store.append_events('a', [event]);
    expect(() => database.read((sql) => view_coverage(sql, 'a'))).toThrow();
    rebuilder.prioritize('c');
    await rebuilder.finish();
    const ids = database.read((sql) =>
      sql.all<{ id: string }>('SELECT id FROM install_order ORDER BY rowid').map((r) => r.id),
    );
    expect(ids).toEqual(['chief', 'a', 'c', 'b']);
    expect(database.read((sql) => view_coverage(sql, 'a'))).toBe(2);
    expect(
      database.read((sql) =>
        sql.all(
          'SELECT sequence FROM conversation_view_rows WHERE conversation_id=? ORDER BY sequence',
          ['a'],
        ),
      ),
    ).toEqual([{ sequence: 1 }, { sequence: 2 }]);
  } finally {
    rebuilder.close();
    await rebuilder.finish();
  }
});
