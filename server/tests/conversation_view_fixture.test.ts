import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { expect, test } from 'vitest';
import type { ConversationEventKind } from '../conversation/events.ts';
import {
  ConversationAccess,
  ConversationBackendKey,
  ResolvedConversationStart,
} from '../conversation/contracts.ts';
import { conversation_event_payload_from_canonical_json } from '../conversation/record/codec.ts';
import { ConversationStorePrimitives } from '../conversation/record/data/store.ts';
import { append_projection } from '../conversation/views/data/writer.ts';
import { read_page } from '../conversation/views/data/storage.ts';
import { fixture as database_fixture } from './ticket_fixture.ts';

interface FixtureEvent {
  sequence: number;
  kind: ConversationEventKind;
  payload: unknown;
  created_at: number;
}
interface Fixture {
  name: string;
  stopped: boolean;
  events: FixtureEvent[];
}
interface Oracle {
  source_sha256: string;
  fixtures: {
    name: string;
    projection: Record<string, unknown[]>;
    pages: Record<'focus' | 'full', unknown>;
  }[];
}
const root = resolve(import.meta.dirname, '../..');
const source = readFileSync(resolve(root, 'tests/fixtures/conversation_views.json'));
const fixtures = JSON.parse(source.toString()) as Fixture[];
const oracle = JSON.parse(
  readFileSync(resolve(root, 'server/conversation/views/fixture_oracle.json'), 'utf8'),
) as Oracle;
const table_order = {
  state: 'conversation_id',
  rows: 'sequence',
  turns: 'source_sequence',
  groups: 'source_sequence',
  lookups: 'lookup_kind,lookup_id',
};

// Required fixture proof: the browser fixture alone cannot prove the SQL projection.
// The oracle is generated by the unchanged Python writer/readers for these same inputs.
// Reuse the existing schema fixture and real write door without another server host.
test('the existing conversation fixtures match Python projection rows and both lens pages', () => {
  expect(createHash('sha256').update(source).digest('hex')).toBe(oracle.source_sha256);
  expect(fixtures.map((value) => value.name)).toEqual(oracle.fixtures.map((value) => value.name));
  for (let index = 0; index < fixtures.length; index++) {
    const fixture = fixtures[index];
    const expected = oracle.fixtures[index];
    const database = database_fixture();
    const store = new ConversationStorePrimitives(database, { integer_now: () => 100 });
    store.create_conversation(
      new ResolvedConversationStart({
        conversation_id: 'fixture',
        backend_key: ConversationBackendKey.hermes,
        model: 'fixture-model',
        reasoning_effort: null,
        role_materials: null,
        workspace_folder: '/fixture',
        access: ConversationAccess.full,
      }),
    );
    database.write((tx) => {
      for (const row of fixture.events) {
        const encoded = JSON.stringify(row.payload);
        tx.run(
          'INSERT INTO conversation_events (conversation_id,sequence,kind,payload,created_at) VALUES (?,?,?,?,?)',
          ['fixture', row.sequence, row.kind, encoded, row.created_at],
        );
        append_projection(tx, [
          {
            conversation_id: 'fixture',
            sequence: row.sequence,
            kind: row.kind,
            payload: conversation_event_payload_from_canonical_json(row.kind, encoded),
            created_at: row.created_at,
          },
        ]);
      }
      tx.run('UPDATE conversations SET latest_sequence=? WHERE conversation_id=?', [
        fixture.events.at(-1)?.sequence ?? 0,
        'fixture',
      ]);
    });
    database.read((sql) => {
      for (const [table, order] of Object.entries(table_order)) {
        expect(
          sql.all(`SELECT * FROM conversation_view_${table} ORDER BY ${order}`),
          `${fixture.name}: ${table}`,
        ).toEqual(expected.projection[table]);
      }
      for (const lens of ['focus', 'full'] as const) {
        expect(
          read_page(sql, 'fixture', lens, { stopped: fixture.stopped }),
          `${fixture.name}: ${lens}`,
        ).toEqual(expected.pages[lens]);
      }
    });
  }
});
