import { closeSync, constants, fsyncSync, openSync } from 'node:fs';
import { open } from 'node:fs/promises';

export async function fsync_path(path: string): Promise<void> {
  const handle = await open(path, 'r');
  try {
    await handle.sync();
  } finally {
    await handle.close();
  }
}

export function fsync_directory_sync(path: string): void {
  const fd = openSync(path, constants.O_RDONLY | constants.O_DIRECTORY);
  try {
    fsyncSync(fd);
  } finally {
    closeSync(fd);
  }
}
