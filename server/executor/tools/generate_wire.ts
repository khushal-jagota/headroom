/** Build the single shared executor wire type file from Python's exported schema. */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';

type Schema = {
  $ref?: string;
  type?: string | string[];
  const?: unknown;
  enum?: unknown[];
  anyOf?: Schema[];
  oneOf?: Schema[];
  allOf?: Schema[];
  properties?: Record<string, Schema>;
  required?: string[];
  additionalProperties?: Schema | boolean;
  items?: Schema | boolean;
  prefixItems?: Schema[];
  minItems?: number;
};
export interface WireSchema {
  $schema: string;
  $defs: Record<string, Schema>;
  roots: string[];
  manifest: Record<string, string | number>;
  event_codecs: Record<string, string>;
}
function canonical(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(canonical);
  if (value !== null && typeof value === 'object')
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, canonical((value as Record<string, unknown>)[key])]),
    );
  return value;
}
const identifier = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
function name(value: string): string {
  if (!identifier.test(value)) throw new Error(`Unsupported schema name: ${value}`);
  return value;
}
function literal(value: unknown): string {
  if (value !== null && !['string', 'number', 'boolean'].includes(typeof value))
    throw new Error('Wire literal must be a scalar');
  return JSON.stringify(value);
}
function render(schema: Schema): string {
  if (schema.$ref !== undefined) {
    if (!schema.$ref.startsWith('#/$defs/'))
      throw new Error(`Unsupported executor schema reference: ${schema.$ref}`);
    return name(schema.$ref.slice('#/$defs/'.length));
  }
  if (Object.hasOwn(schema, 'const')) return literal(schema.const);
  if (schema.enum) return schema.enum.map(literal).join(' | ');
  const union = schema.anyOf ?? schema.oneOf;
  if (union) return union.map((branch) => `(${render(branch)})`).join(' | ');
  if (schema.allOf) return schema.allOf.map((branch) => `(${render(branch)})`).join(' & ');
  if (Array.isArray(schema.type))
    return schema.type.map((type) => `(${render({ ...schema, type })})`).join(' | ');
  switch (schema.type) {
    case 'null':
      return 'null';
    case 'string':
      return 'string';
    case 'boolean':
      return 'boolean';
    case 'integer':
    case 'number':
      return 'number';
    case 'array': {
      if (schema.prefixItems) {
        const entries = schema.prefixItems.map(
          (item, index) => `${render(item)}${index >= (schema.minItems ?? 0) ? '?' : ''}`,
        );
        if (schema.items !== false && schema.items !== undefined)
          entries.push(`...(${schema.items === true ? 'unknown' : render(schema.items)})[]`);
        return `[${entries.join(', ')}]`;
      }
      return `(${typeof schema.items === 'object' ? render(schema.items) : 'unknown'})[]`;
    }
    case 'object': {
      const fields = Object.entries(schema.properties ?? {}).map(
        ([key, value]) =>
          `${JSON.stringify(key)}${schema.required?.includes(key) ? '' : '?'}: ${render(value)};`,
      );
      if (typeof schema.additionalProperties === 'object')
        fields.push(`[key: string]: ${render(schema.additionalProperties)};`);
      else if (schema.additionalProperties !== false && fields.length === 0)
        fields.push('[key: string]: unknown;');
      return `{${fields.join('\n')}}`;
    }
    case undefined:
      if (Object.keys(schema).length === 0) return 'unknown';
      throw new Error(`Unsupported executor schema: ${JSON.stringify(schema)}`);
    default:
      throw new Error(`Unsupported executor schema type: ${schema.type}`);
  }
}
export async function generate_types(schema: WireSchema): Promise<string> {
  schema = canonical(schema) as WireSchema;
  for (const root of schema.roots)
    if (!Object.hasOwn(schema.$defs, root)) throw new Error(`Missing executor root: ${root}`);
  const definitions = Object.entries(schema.$defs)
    .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
    .map(([key, value]) => `export type ${name(key)} = ${render(value)};`);
  const versions = ['protocol_version', 'spool_format_version', 'command_journal_format_version']
    .map((key) => `export const ${key.toUpperCase()} = ${literal(schema.manifest[key])};`)
    .join('\n');
  return format(
    '// Generated by tests/compare/direct/export_unit22_wire.py and server/executor/tools/generate_wire.ts. Do not edit.\n' +
      '// Required nullable fields stay required. Defaults are optional on the wire.\n' +
      `${versions}\n${definitions.join('\n')}\n` +
      `export interface WireTypes {${schema.roots.map((root) => `${name(root)}: ${name(root)};`).join('\n')}}\n` +
      'export type WireRootName = keyof WireTypes;\n',
    { parser: 'typescript', printWidth: 100, singleQuote: true },
  );
}
/** One definition per line keeps a regenerated schema diff local and deduplicated. */
export function schema_text(schema: WireSchema): string {
  schema = canonical(schema) as WireSchema;
  return (
    '{\n' +
    Object.entries(schema)
      .map(([key, value]) =>
        key === '$defs'
          ? `"$defs": {\n${Object.entries(schema.$defs)
              .map(
                ([definition, body]) => `  ${JSON.stringify(definition)}: ${JSON.stringify(body)}`,
              )
              .join(',\n')}\n}`
          : `${JSON.stringify(key)}: ${JSON.stringify(value)}`,
      )
      .join(',\n') +
    '\n}\n'
  );
}
export async function check_wire(
  schema: WireSchema,
  actual: { schema: string; types: string },
): Promise<void> {
  if (actual.schema !== schema_text(schema) || actual.types !== (await generate_types(schema)))
    throw new Error('Executor wire output is stale. Regenerate from current Python.');
}
export async function update_wire(schema: WireSchema, check: boolean): Promise<void> {
  const schema_path = new URL('../wire.schema.json', import.meta.url);
  const types_path = new URL('../wire.generated.ts', import.meta.url);
  if (check) {
    await check_wire(schema, {
      schema: readFileSync(schema_path, 'utf8'),
      types: readFileSync(types_path, 'utf8'),
    });
  } else {
    writeFileSync(schema_path, schema_text(schema));
    writeFileSync(types_path, await generate_types(schema));
  }
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== '--check')) throw new Error('Usage: generate_wire.ts [--check]');
  await update_wire(JSON.parse(readFileSync(0, 'utf8')) as WireSchema, args.includes('--check'));
}
