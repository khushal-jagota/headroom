"""Generate only the selected public measure-source wire contracts."""

from __future__ import annotations

import argparse
import dataclasses
import json
import types
import typing
from enum import Enum
from pathlib import Path
from typing import Any

from planner.credentials.contracts import (
    CreateCredentialRequest,
    CredentialMetadata,
    ReplaceCredentialRequest,
)
from planner.measure_sources.contracts import (
    MeasureSource,
    RunRequestBody,
    SourceRunDetail,
    SourceRunSummary,
    SourceScheduleBody,
    SourceStatus,
)

ROOTS = (
    RunRequestBody,
    SourceStatus,
    MeasureSource,
    SourceRunSummary,
    SourceRunDetail,
    SourceScheduleBody,
    CredentialMetadata,
    CreateCredentialRequest,
    ReplaceCredentialRequest,
)
TARGET = Path(__file__).resolve().parents[1] / "src/lib/measureSources/wire.ts"


def generate() -> str:
    definitions: dict[str, str] = {}

    def render(value: Any) -> str:
        if value is type(None):
            return "null"
        primitives = {str: "string", int: "number", float: "number", bool: "boolean"}
        if value in primitives:
            return primitives[value]
        origin = typing.get_origin(value)
        args = typing.get_args(value)
        if origin in (typing.Union, types.UnionType):
            return " | ".join(render(item) for item in args)
        if origin in (tuple, list):
            return "Array<" + render(args[0]) + ">"
        if origin is typing.Literal:
            return " | ".join(json.dumps(item) for item in args)
        if origin is typing.NotRequired:
            return render(args[0])
        name: str = value.__name__
        if name in definitions:
            return name
        definitions[name] = ""
        if isinstance(value, typing.TypeAliasType):
            body = render(value.__value__)
        elif isinstance(value, type) and issubclass(value, Enum):
            body = " | ".join(json.dumps(item.value) for item in value)
        elif dataclasses.is_dataclass(value) or typing.is_typeddict(value):
            hints = typing.get_type_hints(value, include_extras=True)
            optional: frozenset[str] = getattr(value, "__optional_keys__", frozenset())
            body = (
                "{\n"
                + "".join(
                    f"  {key}{'?' if key in optional else ''}: {render(annotation)};\n"
                    for key, annotation in hints.items()
                )
                + "}"
            )
        else:
            raise TypeError(f"Unsupported public wire annotation: {value!r}")
        definitions[name] = f"export type {name} = {body};\n"
        return name

    for root in ROOTS:
        render(root)
    return (
        "// Generated by web/scripts/measure_source_wire.py from public Python DTOs.\n"
        "// Do not edit by hand. Secrets occur only in write request types.\n\n"
        + "\n".join(definitions.values())
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    result = generate()
    if options.check:
        if TARGET.read_text() != result:
            raise SystemExit(
                "Measure-source wire types differ. Run web/scripts/measure_source_wire.py."
            )
    else:
        TARGET.write_text(result)


if __name__ == "__main__":
    main()
