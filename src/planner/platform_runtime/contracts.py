"""OS contracts reuse the owning domains' identities and evidence."""

from __future__ import annotations

import subprocess
from collections.abc import Mapping
from pathlib import Path
from typing import TYPE_CHECKING, Literal, Protocol

if TYPE_CHECKING:
    from planner.environments.vps_metrics.config import MetricsConfig
    from planner.environments.vps_metrics.contracts import Collector
    from planner.platform_runtime.targets import RuntimeTarget
    from planner.previews.contracts import ProcessIdentity as PreviewIdentity
    from planner.server_lifecycle.contracts import ProcessIdentity, ShutdownPolicy


class UnsupportedPlatformError(RuntimeError):
    """No implementation exists for the requested operating system."""


class PreviewProcessInspector(Protocol):
    def discover(self, port: int, worktree: Path) -> PreviewIdentity: ...
    def check(self, identity: PreviewIdentity, *, deadline: float | None = None) -> None: ...
    def connected(self, identity: PreviewIdentity, local_port: int) -> None: ...


class PlatformAdapter(Protocol):
    @property
    def update_unavailable_reason(self) -> str | None: ...

    def read_process_identity(self, pid: int) -> ProcessIdentity | None: ...
    def read_authenticated_manager_identity(
        self, pid: int, bus: Literal["user", "system"] | None = None
    ) -> ProcessIdentity | None: ...
    def revalidate_manager_identity(self, manager: ProcessIdentity) -> ProcessIdentity | None: ...
    def capture_shutdown_policy(self) -> ShutdownPolicy: ...
    def spawn_application_child(
        self,
        interpreter: str,
        launch_root: Path,
        environment: dict[str, str],
        original_mask: list[int],
    ) -> subprocess.Popen[bytes]: ...
    def process_is_zombie(self, pid: int) -> bool: ...
    def preview_inspector(self) -> PreviewProcessInspector: ...
    def control_socket_path(
        self, port: int, environ: Mapping[str, str], launch_root: Path
    ) -> Path: ...
    def event_loop_tasks_socket_path(self, path: Path) -> Path: ...
    def lifecycle_lease_path(self, port: int) -> Path: ...
    def lock_exclusive(self, descriptor: int, *, nonblocking: bool = False) -> None: ...
    def unlock(self, descriptor: int) -> None: ...
    def metrics_collector(self, config: MetricsConfig) -> Collector: ...

    def own_service_unit(self, cgroup: str | None = None) -> str | None: ...
    def launch_installer(self, attempt_id: str, command: list[str]) -> None: ...
    def installer_source(self) -> Path: ...


class RuntimeRequirements(Protocol):
    """Shared requirements without operating-system-specific native fields."""

    @property
    def system(self) -> str: ...
    @property
    def architecture(self) -> str: ...
    @property
    def python_version(self) -> str: ...
    @property
    def inventory_sha256(self) -> str: ...
    @property
    def external_libraries(self) -> tuple[str, ...]: ...
    @property
    def digest(self) -> str: ...
    def as_dict(self) -> dict[str, object]: ...


class HomeRuntime(Protocol):
    target: RuntimeTarget
    def parse_contract(self, value: object) -> RuntimeRequirements: ...
    def complete_private_runtime(self, app_root: Path) -> RuntimeRequirements: ...
    def verify_host(self, contract: RuntimeRequirements, *, state: Path) -> None: ...
    def native_tool_commands(
        self, root: Path, contract: RuntimeRequirements
    ) -> list[list[str]]: ...
